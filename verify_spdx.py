#!/usr/bin/env python3
"""Verify SPDX tags were correctly inserted in all source files.

Checks per file:
  1. First line is still a copyright header start (comment-style aware)
  2. SPDX tag exists in the first 10 lines
  3. SPDX tag immediately follows the HEADER END line
  4. File is not truncated (still has substantial content)
  5. No null bytes introduced
  6. Header END line still present

Expanded file set: C/C++ headers/sources, GPU shaders, UI resources (.ui, .qrc),
and CMake manifests (CMakeLists.txt, *.cmake). CMake files use '#' comment syntax;
all others use '//'.
"""
import os
import sys

ROOT = os.path.dirname(os.path.abspath(__file__))
SOURCE_DIRS = ['source', 'components']
# Expanded file set: C/C++/GPU shaders + UI resources + CMake manifests
EXTS = ('.cpp', '.hpp', '.h', '.c', '.ui', '.qrc', '.cmake')
CMAKE_FILES = ('CMakeLists.txt',)
SPDX_TAG = 'SPDX-License-Identifier: GPL-3.0-or-later'
HEADER_START = 'AUTOGENERATED COPYRIGHT HEADER START'
HEADER_END = 'AUTOGENERATED COPYRIGHT HEADER END'


def get_comment_prefix(fname):
    """Return the expected comment prefix for this file type."""
    if fname in CMAKE_FILES or fname.endswith('.cmake'):
        return '#'
    # .ui/.qrc use XML <!-- --> comments; .cpp/.hpp/.h/.c/.glsl/.vert/.frag use //
    return None  # None → handle as C-style or XML


def main():
    issues = []
    count = 0

    for base in SOURCE_DIRS:
        base_path = os.path.join(ROOT, base)
        for dirpath, dirnames, filenames in os.walk(base_path):
            for fname in filenames:
                if not (fname.endswith(EXTS) or
                        fname in CMAKE_FILES):
                    continue
                fpath = os.path.join(dirpath, fname)
                relpath = os.path.relpath(fpath, ROOT)
                count += 1

                with open(fpath, 'r', encoding='utf-8') as f:
                    lines = f.readlines()

                # Determine comment style
                is_cmake = fname in CMAKE_FILES or fname.endswith('.cmake')
                is_xml = fname.endswith('.ui') or fname.endswith('.qrc')

                if is_cmake:
                    comment_start = '#'
                    header_start_marker = f'{comment_start} {HEADER_START}'
                    header_end_marker = f'{comment_start} {HEADER_END}'
                elif is_xml:
                    header_start_marker = f'<!-- {HEADER_START} -->'
                    header_end_marker = f'<!-- {HEADER_END} -->'
                else:
                    header_start_marker = f'// {HEADER_START}'
                    header_end_marker = f'// {HEADER_END}'

                # Check first line is still header start
                first_stripped = lines[0].strip() if lines else ''
                if not (first_stripped.startswith(header_start_marker) or
                        first_stripped.startswith(HEADER_START)):
                    issues.append(
                        f'{relpath}: first line is not header start: '
                        f'{lines[0].strip()!r}'
                    )

                # Check HEADER END still present (look in first 25 lines for CMake)
                check_lines = lines[:25] if is_cmake else lines[:20]
                if HEADER_END not in ''.join(check_lines):
                    issues.append(
                        f'{relpath}: HEADER END not found in first '
                        f'{len(check_lines)} lines'
                    )

                # Check SPDX tag exists in first 10 lines
                spdx_found = False
                for i, line in enumerate(lines[:10]):
                    if SPDX_TAG in line:
                        spdx_found = True
                        # Check SPDX immediately follows the header END line
                        if i > 0:
                            prev_stripped = lines[i - 1].strip()
                            if HEADER_END not in prev_stripped:
                                issues.append(
                                    f'{relpath}: SPDX not immediately after '
                                    f'header END (line {i})'
                                )
                        break

                if not spdx_found:
                    issues.append(
                        f'{relpath}: SPDX tag not found in first 10 lines'
                    )

                # Check file not truncated
                if len(lines) < 5:
                    issues.append(
                        f'{relpath}: file too short ({len(lines)} lines)'
                    )

                # Check no null bytes
                with open(fpath, 'rb') as f:
                    raw = f.read()
                if b'\x00' in raw:
                    issues.append(f'{relpath}: contains null bytes')

    print(f'Total files checked: {count}')
    print(f'Issues found: {len(issues)}')
    for issue in issues[:20]:
        print(f'  {issue}')
    if len(issues) > 20:
        print(f'  ... and {len(issues) - 20} more')
    sys.exit(1 if issues else 0)


if __name__ == '__main__':
    main()
