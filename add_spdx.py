#!/usr/bin/env python3
"""Add SPDX-License-Identifier: GPL-3.0-or-later tags to all source files.

Inserts the SPDX tag as a new line immediately after the AUTOGENERATED
COPYRIGHT HEADER END line. For files missing the header entirely, the tag
is prepended at the top of the file.

Expanded file set: C/C++/GPU shaders, UI resources (.ui, .qrc),
and CMake manifests (CMakeLists.txt, *.cmake).
  - CMake files use '#' comment syntax
  - .ui/.qrc files use XML '<!-- -->' comment syntax
  - All other extensions use '//' comment syntax
"""
import os
import sys

ROOT = os.path.dirname(os.path.abspath(__file__))
SOURCE_DIRS = ['source', 'components']
EXTS = ('.cpp', '.hpp', '.h', '.c', '.ui', '.qrc', '.cmake')
CMAKE_FILES = ('CMakeLists.txt',)


def get_comment_style(fname):
    """Return (comment_prefix, spdx_line, header_start, header_end) for file type."""
    if fname in CMAKE_FILES or fname.endswith('.cmake'):
        return ('#', '# SPDX-License-Identifier: GPL-3.0-or-later',
                '# AUTOGENERATED COPYRIGHT HEADER START',
                '# AUTOGENERATED COPYRIGHT HEADER END')
    elif fname.endswith('.ui') or fname.endswith('.qrc'):
        return ('<!--', '<!-- SPDX-License-Identifier: GPL-3.0-or-later -->',
                '<!-- AUTOGENERATED COPYRIGHT HEADER START -->',
                '<!-- AUTOGENERATED COPYRIGHT HEADER END -->')
    else:
        return ('//', '// SPDX-License-Identifier: GPL-3.0-or-later',
                '// AUTOGENERATED COPYRIGHT HEADER START',
                '// AUTOGENERATED COPYRIGHT HEADER END')


def main():
    count = 0
    already = 0
    errors = []

    for base in SOURCE_DIRS:
        base_path = os.path.join(ROOT, base)
        for dirpath, dirnames, filenames in os.walk(base_path):
            for fname in filenames:
                if not (fname.endswith(EXTS) or
                        fname in CMAKE_FILES):
                    continue
                fpath = os.path.join(dirpath, fname)
                relpath = os.path.relpath(fpath, ROOT)

                comment_prefix, spdx_tag, header_start, header_end = get_comment_style(fname)

                try:
                    with open(fpath, 'r', encoding='utf-8') as f:
                        content = f.read()

                    if 'SPDX-License-Identifier' in content:
                        already += 1
                        continue

                    if header_end in content:
                        new_content = content.replace(
                            header_end + '\n',
                            header_end + '\n' + spdx_tag + '\n',
                            1
                        )
                    else:
                        new_content = spdx_tag + '\n' + content

                    with open(fpath, 'w', encoding='utf-8') as f:
                        f.write(new_content)
                    count += 1
                except Exception as e:
                    errors.append((relpath, str(e)))

    print(f'Files modified: {count}')
    print(f'Files already had SPDX (skipped): {already}')
    print(f'Total processed: {count + already}')
    if errors:
        print(f'Errors: {len(errors)}')
        for fpath, err in errors:
            print(f'  {fpath}: {err}')
        sys.exit(1)


if __name__ == '__main__':
    main()
